#pragma once

#include <QByteArray>

/**
 * Запечатать байты так, чтобы копия файла на чужой машине была бесполезна.
 *
 * ЗАЧЕМ ОТДЕЛЬНЫЙ СЛОЙ. Реквизиты доступа нельзя класть в profiles/*.json:
 * те пишутся открытым текстом (JsonStore::Save) и открываются одним пунктом
 * меню «Открыть папку конфигурации». Человек, приславший в поддержку «папку с
 * настройками», прислал бы вместе с ней и ключи.
 *
 * ЧТО ЭТО ДАЁТ И ЧЕГО НЕ ДАЁТ. Защита от переноса, а не от владельца машины.
 * Тот, кто уже выполняет код от имени этого пользователя, распечатает блоб тем
 * же вызовом, что и мы. Обещать здесь больше — врать; ровно поэтому у каждой
 * реализации ниже честно написано, чего она стоит.
 *
 * Пустой QByteArray на выходе означает отказ. Вызывающий обязан считать это
 * «реквизитов нет» и попросить активацию заново, а не работать с мусором.
 */
namespace SealedStore {
    QByteArray Seal(const QByteArray &plain);
    QByteArray Unseal(const QByteArray &sealed);

    /**
     * Чем запечатано — одной строкой, для журнала и диагностики.
     *
     * Нужна, чтобы отчёт поддержки отвечал на вопрос «почему у него реквизиты
     * не пережили перенос профиля», не заставляя гадать по платформе.
     */
    QString Kind();
} // namespace SealedStore
