#pragma once

/*
 * Когда внешний туннель поднимать и когда снимать.
 *
 * ЗАЧЕМ ЭТО ЕСТЬ. На macOS туннель — отдельный процесс от root, и весь его
 * трафик уходит в SOCKS-вход ОСНОВНОГО ядра на 127.0.0.1. Пока профиль не
 * подключён, этого порта нет. Поднять туннель раньше — значит увести весь мак
 * в закрытый порт: ни одной страницы, ни одного запроса DNS. Ровно так это и
 * выглядело у тестировщика: «включил туннель — всё умерло». То же самое при
 * отключении профиля с поднятым туннелем.
 *
 * Поэтому порядок закреплён здесь двумя чистыми правилами, а не разбросан по
 * обработчикам: туннель поднимается ПОСЛЕ удачного старта профиля и снимается
 * ДО остановки основного ядра.
 *
 * ЧЕГО ПРАВИЛА НАМЕРЕННО НЕ ДЕЛАЮТ.
 *
 *  — Не снимают туннель при передаче между профилями (handOver): ядро
 *    останавливается и тут же запускается снова, порт возвращается через
 *    секунду, а снятие и подъём стоили бы два запроса пароля на каждую смену
 *    сервера.
 *
 *  — Не снимают туннель на путях без человека (unattended): падение ядра или
 *    внешнего процесса. Снятие на маке — это запрос пароля, и появляться
 *    посреди аварии, когда его никто не ждёт, он не должен: отменённый запрос
 *    обрывал остановку на полпути, а не отвеченный за полминуты читался как
 *    удача. Ядро после падения перезапускается само, порт возвращается,
 *    помощник остаётся на месте — и второй не поднимается, потому что первый
 *    ещё жив (processRunning).
 *
 * Замысел и первая реализация — от тестировщика с маком (сентябрь 2026).
 */
namespace GreenRhythm::TunLifecycle {

    /** Поднимать ли внешний туннель после удачного старта профиля. */
    constexpr bool shouldStartExternal(bool requested, bool internalTun,
                                       bool profileConnected, bool processRunning) {
        return requested && !internalTun && profileConnected && !processRunning;
    }

    /** Снимать ли внешний туннель перед остановкой основного ядра. */
    constexpr bool shouldStopExternalBeforeDisconnect(bool requested, bool internalTun,
                                                      bool processRunning, bool handOver,
                                                      bool unattended) {
        return requested && !internalTun && processRunning && !handOver && !unattended;
    }

} // namespace GreenRhythm::TunLifecycle
