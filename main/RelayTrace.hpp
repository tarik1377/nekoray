#pragma once

#include <QString>

/**
 * Единственная дорога, по которой вывод резервного подключения попадает в журнал.
 *
 * ЗАЧЕМ ЭТО ВООБЩЕ ЕСТЬ. Внешние ядра пишут в журнал как есть: ExternalProcess
 * подписан на stdout и stderr и отдаёт всё в MW_show_log_ext_vt100, а журнал
 * пишется в файл и уезжает в поддержку через collect-report.ps1. Для xray это
 * правильно — там в выводе адреса серверов, которые человек и так знает, потому
 * что сам их добавил. Для резервного подключения это недопустимо: его вывод
 * называет устройство канала, а владелец запретил рассказывать об этом в любом
 * тексте, который видит посторонний.
 *
 * ТО ЖЕ РЕШЕНИЕ УЖЕ ПРИНЯТО НА ANDROID, и принято дорогой ценой: там сырой
 * вывод убрали из журнала целиком (см. ConnectTrace.java), потому что он
 * называл транспорт, имена порций и адреса. Здесь повторяется тот же приём, а
 * не изобретается новый — иначе две ветки разойдутся молча.
 *
 * КАК УСТРОЕНО. Из строки движка НЕ ПЕРЕНОСИТСЯ НИ ОДНОГО СИМВОЛА. Разбираются
 * целые числа по жёсткому курсору, и русская фраза собирается заново из них.
 * Строка, в которой есть хоть что-то сверх формата, отвергается целиком — и
 * именно это не пускает в журнал адрес, приписанный за форматом.
 *
 * Формат закреплён с той стороны в native-src/warmlog.go и покрыт там тестами
 * TestTheWarmMilestoneCarriesOnlyNumbers и TestTheCarryMilestoneCarriesOnlyNumbers.
 * Движок приезжает готовым бинарём и обновляется отдельно от клиента, поэтому
 * согласовать две стороны можно только назвав формат в одном месте на каждой.
 */
namespace RelayTrace {
    /**
     * Что показать в журнале вместо строки движка.
     *
     * Пустая строка означает «показывать нечего»: либо это не веха, либо веха
     * испорчена. Вызывающий обязан в этом случае промолчать, а не показать
     * исходную строку — молчание здесь дешевле утечки.
     */
    QString Line(const QString &engineLine);
} // namespace RelayTrace
