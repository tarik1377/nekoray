#pragma once

#include "DeviceCredentials.hpp"

#include <QByteArray>
#include <QString>

/**
 * Активация резервного подключения на этом устройстве.
 *
 * ДВА ШАГА, ОБА УЖЕ ЕСТЬ НА САЙТЕ — новых эндпоинтов не потребовалось:
 *   POST /api/auth/app-code/redeem  — восьмизначный код из кабинета → токен
 *   POST /api/relay/device          — токен → реквизиты доступа
 *
 * ПОЧЕМУ КОДОМ, А НЕ ЛОГИНОМ С ПАРОЛЕМ. Часть клиентов зарегистрирована через
 * Telegram и пароля не имеет вовсе — это и есть причина, по которой код вообще
 * появился. Плюс клиент не должен уметь принимать пароли: поле, которого нет,
 * невозможно ни подсмотреть, ни залогировать.
 *
 * РАЗБОР ОТВЕТОВ ВЫНЕСЕН В ЧИСТЫЕ ФУНКЦИИ. Это тот же протокол, что на Android
 * (Provisioning.java:78-125), и расходиться им нельзя: 402 требует СТЕРЕТЬ
 * реквизиты, а сетевой сбой — не трогать ничего, потому что «сеть не ответила»
 * не доказывает, что доступ кончился. Перепутать эти две ветки значит либо
 * отключить человека на ровном месте, либо оставить ему нерабочие ключи.
 */
namespace RelayActivation {

    struct Outcome {
        bool ok = false;
        DeviceCredentials::State state = DeviceCredentials::Unknown;
        QString detail;
        /** Куда вести человека, если отказ лечится действием на сайте. */
        QString actionUrl;
        QString actionText;

        /**
         * Сайт СКАЗАЛ, что доступа больше нет — реквизиты надо стереть.
         *
         * Отдельный признак, а не вывод из state, и это не педантизм. При сбое
         * сети state возвращается ПРЕЖНИЙ, и если прежним было «подписка
         * кончилась», решение «стереть, раз Expired» сработало бы на ровном
         * месте — от того, что у человека на секунду пропал интернет. Ставится
         * ровно в одной ветке: 402.
         */
        bool revoked = false;
    };

    /** Адрес кабинета, где берут код. Якорь — карточка выдачи кода. */
    QString ProfileUrl();

    /**
     * Разбор ответа на обмен кода. status 0 — до сервера не дошли.
     *
     * token заполняется только при успехе; при отказе он пуст, и вызывающий
     * обязан ничего не сохранять.
     */
    Outcome InterpretRedeem(int status, const QByteArray &body, const QString &networkError,
                            QString *token);

    /**
     * Разбор ответа на выдачу реквизитов.
     *
     * issued заполняется только при успехе и только если конфигурация полна:
     * половина полей хуже, чем ничего, — с ней подключение молча не поднимется.
     */
    Outcome InterpretDevice(int status, const QByteArray &body, const QString &networkError,
                            QJsonObject *issued);

    /** Обменять код на токен и сохранить его. Блокирующий вызов. */
    Outcome Redeem(const QString &code);

    /**
     * Запросить реквизиты по сохранённому токену и сохранить их.
     * Блокирующий вызов. Зовётся при активации, по сроку и перед запуском.
     */
    Outcome Provision();

    /** Забыть всё на этом устройстве. Сайту при этом ничего не говорим. */
    void Forget();

} // namespace RelayActivation
