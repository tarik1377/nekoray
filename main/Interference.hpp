#pragma once

#include <QList>
#include <QString>
#include <QStringList>

/**
 * Что мешает подключению — и как это ВРЕМЕННО убрать с дороги.
 *
 * ЗАЧЕМ ОТДЕЛЬНО ОТ «ПОЧИНИТЬ СЕТЬ». Та кнопка сносит навсегда: службу удаляет,
 * драйвер снимает, автозапуск вычищает. Это правильно для брошенного zapret,
 * который человек ставил полгода назад и забыл. И это категорически неправильно
 * для работающего Cloudflare WARP, корпоративного клиента или туннеля до дома:
 * человек хотел подключиться на полчаса, а остался без рабочего VPN навсегда и
 * без способа вернуть его нашими руками.
 *
 * Поэтому здесь третий путь, которого не было: ПРИОСТАНОВИТЬ И ВЕРНУТЬ.
 * Прежнее состояние каждой службы и каждого адаптера записывается в снимок ДО
 * остановки, и возвращается при отключении, при выходе и — отдельно — при
 * следующем запуске, если клиент не пережил прошлый раз.
 *
 * ЧЕТЫРЕ ПРАВИЛА, КАЖДОЕ ОПЛАЧЕНО ЧУЖИМ СЛОМАННЫМ ДНЁМ.
 *
 *  1. НИЧЕГО НЕ ТРОГАЕМ БЕЗ ГАЛОЧКИ. Список показывается целиком, решение
 *     принимает человек по каждой строке. Автоматика здесь означала бы, что мы
 *     угадали, что у него на машине лишнее, — а прошлый раз, когда мы угадывали,
 *     выключился туннель до его дома.
 *
 *  2. ВОЗВРАТ ВАЖНЕЕ ОСТАНОВКИ. Снимок пишется на диск и сбрасывается на диск
 *     ДО первой остановки. Порядок обратный — «сначала остановим, потом
 *     запишем» — стоил бы человеку рабочего VPN ровно в тот момент, когда мы
 *     упали между двумя действиями.
 *
 *  3. НЕОБРАТИМОЕ НЕ ПРЕДЛАГАЕМ. Строка, для которой мы не умеем вернуть как
 *     было, показывается, но без галочки: пусть человек решает сам и своими
 *     руками. Предложить кнопку и не суметь откатить — хуже, чем не предлагать.
 *
 *  4. СВОЁ УЗНАЁМ ПО ПУТИ. Наш модуль обхода и наш собственный туннель в этот
 *     список не попадают никогда — тем же приёмом, что и в «Починить сеть».
 *
 * Разбор и построение скриптов здесь чистые: ни PowerShell, ни диалогов. Всё,
 * что трогает систему, живёт в ui/Interference*.cpp и зовёт эти функции.
 */
namespace GreenRhythm {

    enum class Meddler {
        Service, ///< служба Windows
        Adapter, ///< сетевой адаптер (туннель чужого клиента)
        Driver,  ///< фильтрующий драйвер
        Process, ///< запущенная программа
        Filter,  ///< запись WFP или LSP — только показать
    };

    struct Meddling {
        Meddler kind = Meddler::Service;
        QString key;    ///< имя службы, адаптера или процесса — по нему и действуем
        QString title;  ///< как назвать человеку
        QString detail; ///< состояние и путь, одной строкой
        bool running = false;
        /**
         * Умеем ли вернуть как было. Только у таких строк есть галочка —
         * см. правило 3.
         */
        bool reversible = false;
        /** Чем грозит остановка. Пусто — ничем, кроме потери самой программы. */
        QString risk;
    };

    /** Разведка: PowerShell БЕЗ прав администратора. Читает, ничего не меняет. */
    QString scanScript();

    /** Разбор вывода разведки. Строка с меньшим числом полей отбрасывается молча. */
    QList<Meddling> parseScan(const QString &raw);

    /**
     * Остановить выбранное, записав прежнее состояние в снимок.
     *
     * Снимок пишется ПЕРВЫМ действием и сбрасывается на диск до первой
     * остановки — см. правило 2.
     */
    QString pauseScript(const QList<Meddling> &chosen, const QString &snapshotPath);

    /** Вернуть всё из снимка и удалить его. Пустой снимок — пустая работа. */
    QString resumeScript(const QString &snapshotPath);

    /** Строки снимка человеческими словами: что именно вернём. */
    QStringList snapshotSummary(const QString &snapshot);

    /** Полное имя файла снимка. Рядом с профилями, а не рядом с бинарём. */
    QString snapshotPath();

    // ── Живая часть ──────────────────────────────────────────────────────
    //
    // Определения — в ui/dialog_interference.cpp: там PowerShell, повышение
    // прав и окно. Здесь только объявления, чтобы окно могло звать возврат, не
    // зная про диалог. Набор проверок их не линкует и не зовёт: всё, что можно
    // проверить без живой Windows, лежит выше.

    /** Разведка на этой машине. Пусто — ничего не нашли (или не Windows). */
    QList<Meddling> scanInterference();

    /**
     * Вернуть всё приостановленное и убрать снимок.
     *
     * @param said куда положить перечень возвращаемого; можно nullptr
     * @return true, если вернули или возвращать было нечего
     */
    bool resumeInterference(QString *said);

    /** Есть ли что возвращать. Дешёвая: смотрит только наличие файла снимка. */
    bool interferencePaused();

} // namespace GreenRhythm
