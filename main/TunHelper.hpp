#pragma once

#include <QString>
#include <QStringList>

/*
 * Помощник внешнего туннеля: имена файлов, разбор ответов системы и сборка
 * команд. Чистый модуль без QProcess — ровно затем, чтобы каждую строку можно
 * было проверить на Windows, где мака нет (test/TunHelperTest.cpp).
 *
 * ЗАЧЕМ ОН ЕСТЬ. На macOS туннель — отдельный процесс от root, запущенный через
 * osascript, а тот отдаёт вывод только ПОСЛЕ завершения команды. Пока помощник
 * жив, приложение не видит от него ни строки, и «туннель не работает» долго не
 * имело ни одной подробности: лог основного ядра про помощника молчит по
 * устройству, а не потому, что помощника нет. Теперь скрипт
 * (res/vpn/vpn-run-root.sh) пишет номер процесса и журнал в файлы рядом с
 * конфигом, приложение читает их по мере записи и само проверяет цепочку:
 * помощник жив → устройство поднято → маршрут через него → порт ядра слушает →
 * ответ из сети приходит. Первое разорванное звено называется человеку словами.
 */
namespace GreenRhythm::TunHelper {

    /** Имена файлов, которые пишет скрипт. Закреплены набором вместе со скриптом. */
    QString pidPath(const QString &configDir);
    QString logPath(const QString &configDir);

    /** Номер процесса из текста файла; 0 — в нём не число. */
    qint64 parsePid(const QString &text);
    /** То же из файла; 0 — файла нет. */
    qint64 readPid(const QString &configDir);

    /**
     * Новые строки журнала начиная с offset. Возвращает новый offset —
     * позицию после последней ПОЛНОЙ строки: недописанный хвост остаётся до
     * следующего чтения, а не уезжает в журнал половиной. Файл стал короче
     * (скрипт начал заново) — чтение идёт с начала.
     */
    qint64 readNewLines(const QString &path, qint64 offset, QStringList &out);

    /** Последние n непустых строк файла — для сообщения человеку. Пусто — файла нет. */
    QString lastLines(const QString &path, int n);

    /** Интерфейс из вывода `route -n get <адрес>` (строка «interface: en0»). Пусто — не найден. */
    QString routeInterface(const QString &routeGetOutput);

    /** Имя интерфейса из `ifconfig -a`, на котором стоит адрес. Пусто — ни на одном. */
    QString interfaceWithAddress(const QString &ifconfigOutput, const QString &addr);

    /** Путь в одинарных кавычках оболочки: пробелы и доллары внутри не трогаются. */
    QString shellSingleQuote(const QString &s);
    /** Строка как литерал AppleScript: экранированы обратный слэш и кавычка. */
    QString appleScriptLiteral(const QString &s);
    /**
     * Команда запуска скрипта для `do shell script` — оба уровня кавычек.
     *
     * Путь на маке содержит пробел («Application Support») и проходит два
     * разбора: сначала как литерал AppleScript, потом его содержимое — оболочкой.
     * Собранная без кавычек, она превращалась в `bash /Users/x/Library/Application`
     * — туннель не запускался никогда. Порядок важен: сначала кавычки оболочки,
     * затем экранирование AppleScript.
     */
    QString macStartCommand(const QString &scriptPath);

    /**
     * Команда снятия помощника для `do shell script`.
     *
     * ИМЯ ПРОЦЕССА ПРОВЕРЯЕТСЯ ПЕРЕД СИГНАЛОМ. Номер берётся из файла, а файл
     * переживает своего хозяина: выключение мака убивает оболочку внутри wait,
     * и убрать за собой она не успевает. После перезагрузки номера начинаются
     * заново, и тот же номер достаётся чужой программе — которой мы бы послали
     * сигнал от root. Поэтому сигнал идёт, только если под этим номером и
     * правда ядро; иначе — обход всех ядер от root, кроме основного
     * (mainCorePid): у интерфейса, запущенного от root, основное ядро тоже
     * root, и «убить все» отключало и его.
     *
     * Двойных кавычек в команде нет намеренно: она идёт литералом AppleScript,
     * и кавычка внутри разорвала бы его.
     */
    QString macStopCommand(qint64 helperPid, qint64 mainCorePid);

    /** Отказ osascript из-за отменённого запроса пароля (код -128 в конце). */
    bool looksCancelled(const QString &osascriptOutput);

    /** То же с учётом кода возврата: pkexec на Linux отвечает 126. */
    bool looksCancelledExit(int exitCode, const QString &output);

    /** Наш адрес на устройстве туннеля — из шаблона res/vpn/sing-box-vpn.json. */
    QString ourAddress();

    /** Что проверяется после подъёма. Каждое поле — одно звено цепочки. */
    struct Chain {
        bool helperAlive = false;   // процесс с номером из файла жив
        QString adapter;            // устройство с нашим адресом; пусто — не поднято
        QString routeVia;           // интерфейс маршрута к 1.1.1.1
        bool socksOpen = false;     // SOCKS-порт основного ядра слушает
        bool throughTunnel = false; // ответ из сети получен, а не только рукопожатие
    };

    /**
     * Первое разорванное звено словами для человека; пусто — цепочка цела.
     * Порядок проверки — порядок, в котором идёт трафик: помощник, устройство,
     * маршрут, порт ядра, сквозное соединение.
     */
    QString firstBrokenLink(const Chain &c, const QString &socksAddr, int socksPort);

} // namespace GreenRhythm::TunHelper
