#pragma once

#include <QJsonObject>
#include <QString>

/**
 * Реквизиты доступа этого устройства к резервному подключению.
 *
 * ЧТО ЗДЕСЬ ЛЕЖИТ И ЧЕГО ЗДЕСЬ НЕТ. Здесь — то, что сайт выдал по активации:
 * адрес, ключи, производный ключ устройства и его тег. Плюс токен сессии и
 * идентификатор установки. В профиле подключения (profiles/*.json) не лежит
 * НИЧЕГО из этого: профиль — это включатель, а не носитель доступа. Иначе
 * человек, отправивший в поддержку «папку с настройками», отправил бы и ключи.
 *
 * ПОЧЕМУ ТОКЕН ЗДЕСЬ ЖЕ, А НЕ РЯДОМ. Это прямой урок Android (SecureStore.java,
 * раздел «СЕССИЯ — ТОЖЕ ЗДЕСЬ»): токен в открытом виде рядом с запечатанным
 * блобом снимает смысл запечатывания, потому что по токену сайт выдаст всё
 * заново. Хранить два уровня секретности в одном месте — это не небрежность, а
 * следствие того, что нижний уровень позволяет получить верхний.
 *
 * ЖИЗНЬ В ПАМЯТИ. Распечатанное держится в памяти процесса, пока приложение
 * работает, — как Settings.load() на Android. Перечитывать файл на каждый
 * запуск профиля значило бы распечатывать блоб чаще, чем нужно.
 */
namespace DeviceCredentials {

    /** Состояние доступа — то, что показывают человеку, не спрашивая сеть. */
    enum State {
        Unknown,   ///< ещё не спрашивали
        Active,    ///< доступ есть
        SignedOut, ///< не активировано на этом устройстве
        Expired,   ///< подписка кончилась (402)
        Limit,     ///< упёрлись в лимит устройств по тарифу (409)
        Closed,    ///< канал не открыт для этого аккаунта (403 relay_admin_only)
    };

    /** Есть ли на этом устройстве полные реквизиты. */
    bool IsProvisioned();

    /** Пора ли перепроверить их на сайте. Тот же срок, что на Android, — 6 часов. */
    bool NeedsRefresh();

    /** Последнее известное состояние и человеческая строка к нему. */
    State CurrentState();
    QString StateDetail();

    /** Идентификатор установки. Заводится один раз и переживает перезапуски. */
    QString DeviceId();

    /**
     * Токен сессии для запросов к сайту. Пустая строка — не активировано.
     * Наружу отдаётся только вызывающему, который сейчас же его и потратит.
     */
    QString Token();

    /**
     * Одно поле выданной конфигурации: endpoint, bucket, key, secret, psk, tag.
     *
     * Значения не логируются и не показываются человеку нигде — ни в диалоге,
     * ни в редакторе профиля, ни в экспорте конфига.
     */
    QString Field(const QString &name);

    /** Сохранить ответ активации. false — не сохранилось, доступ считать прежним. */
    bool Save(const QString &token, const QJsonObject &issued);

    /**
     * Сохранить ТОЛЬКО ключ сессии, без выданной конфигурации.
     *
     * Отдельный метод, потому что шага два и они разнесены во времени: код
     * меняется на ключ, ключом запрашиваются реквизиты. Между ними ключ уже
     * надо иметь на руках — код одноразовый, и если сохранить его нечем, сбой
     * на втором шаге заставит человека брать новый код.
     *
     * Save сюда не годится: он требует полной конфигурации и на пустой
     * возвращает false, ничего не записав. Именно так и было сделано сначала —
     * ключ молча не сохранялся, и активация ломалась целиком.
     */
    bool SaveToken(const QString &token);

    /** Запомнить состояние, не трогая сами реквизиты (для 409, сетевых сбоев). */
    void Remember(State state, const QString &detail);

    /** Стереть всё. После этого подключиться по резерву нельзя. */
    void Wipe();

    /** Прочитать с диска. Зовётся один раз при старте. */
    void Load();

    /** Полны ли выданные поля — та же проверка, что Provisioning.complete. */
    bool Complete(const QJsonObject &issued);

} // namespace DeviceCredentials
