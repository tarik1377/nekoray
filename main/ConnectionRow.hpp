#pragma once

#include <QString>

/**
 * Как подписать строку в таблице соединений.
 *
 * Три подписи, и все три раньше жили внутри цикла перерисовки таблицы, где их
 * нельзя было ни проверить, ни показать в снимке. Вынесены сюда чистыми
 * функциями: ни окна, ни ядра, только строки.
 *
 * ЧТО БЫЛО НЕ ТАК НА СНИМКЕ ВЛАДЕЛЬЦА (05.09.2026).
 *
 *  — Назначение писалось как «[149.154.167.41:443] a.claude.ai:443»: адрес
 *    в скобках впереди, имя следом, порт дважды. Глаз ищет имя, а имя стоит
 *    вторым. Теперь имя первое, адрес приглушённым хвостом, порт один раз.
 *
 *  — Три строки «— · Напрямую · 185.194.32.150:1193» выглядели как неизвестные
 *    программы, идущие мимо VPN. Это ядро держит туннель к серверу профиля:
 *    у соединения нет процесса, потому что процесс — мы сами. Теперь такая
 *    строка так и подписана, и «мимо VPN» она больше не изображает.
 */
namespace GreenRhythm {

    /** «a.b.c:443» → «a.b.c»; «[::1]:443» → «::1»; голый IPv6 не трогается. */
    QString hostWithoutPort(const QString &hostPort);

    /**
     * Подпись назначения.
     *
     * Есть имя — «имя:порт  ·  адрес», адрес без порта. Имени нет или оно
     * совпадает с адресом — «адрес:порт» как есть.
     */
    QString destinationLabel(const QString &dest, const QString &resolved);

    /**
     * Подпись программы.
     *
     * Имя процесса, если ядро его отдало. Иначе, если адрес назначения — сервер
     * профиля, это наш собственный туннель, и он так и называется. Иначе «—».
     */
    QString programLabel(const QString &process, const QString &dest, const QString &serverHost);

    /** Подпись нашего туннеля — одна на таблицу и на подсказку. */
    QString tunnelLabel();

} // namespace GreenRhythm
