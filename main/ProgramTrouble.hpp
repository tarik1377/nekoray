#pragma once

#include <QList>
#include <QSet>
#include <QString>
#include <QStringList>

namespace GreenRhythm {

    /**
     * Одно соединение, как его прислало ядро.
     *
     * Поля повторяют uiConnection (go/cmd/nekobox_core/connections.go). Network и
     * Rule здесь не для красоты: без них нельзя отличить намеренный порядок от
     * поломки, а без network — сломанный у игры UDP от её же исправного HTTPS.
     */
    struct Seen {
        QString process;
        QString tag;     // proxy | direct | bypass | block
        QString network; // tcp | udp
        QString dest;
        QString rule;
        qint64 start = 0;
        qint64 end = 0;
    };

    enum class Verdict {
        NotSeen,       // за время наблюдения программа не связывалась ни с кем
        ThroughTunnel, // ходит через туннель — вот и причина
        Direct,        // и так ходит напрямую — причина не в нас
        Mixed,         // часть через туннель, часть напрямую
    };

    struct Finding {
        Verdict verdict = Verdict::NotSeen;
        QString name;   // имя программы, КАК ЕЁ ВИДИТ ЯДРО
        int viaTunnel = 0;
        int direct = 0;
        int udpViaTunnel = 0; // для игр решает именно это
        QStringList companions;
    };

    /**
     * Наблюдение за одной программой.
     *
     * ЗАЧЕМ ОТДЕЛЬНЫМ СЛОЕМ. Здесь нет ни одного виджета и ни одного обращения к
     * ядру — только счёт по присланным записям. Поэтому приговор проверяется
     * набором, а не глазами на живой машине, где для каждой проверки пришлось бы
     * ломать себе сеть.
     *
     * ПОЧЕМУ СЧЁТ НЕ ПРОСТОЙ. Ядро присылает одно и то же соединение в каждом
     * опросе: живое — пока живо, закрытое — ещё две минуты после смерти. Считать
     * записи «как есть» значит умножить одно долгое соединение на число опросов;
     * счётчик покажет «30 обращений» там, где было одно. Поэтому каждое
     * соединение опознаётся по неизменной тройке и учитывается однажды.
     *
     * ЧЕГО ЭТОТ СЛОЙ НЕ ВИДИТ. Запрещённых соединений. Запрет в ядре —
     * действие правила, и до учёта дело не доходит вовсе. Поэтому пустой счётчик
     * запретов означает «не знаем», а не «запретов не было, всё хорошо», и
     * приговора «программу не пускают» здесь нет и быть не может.
     */
    class Watch {
    public:
        /** Очередной ответ ядра. Повторы отсеиваются сами. */
        void add(const QList<Seen> &batch);

        /** Приговор по названной программе. Имя сравнивается без учёта регистра. */
        Finding finish(const QString &program) const;

        /** Сколько разных соединений замечено всего — для строки хода наблюдения. */
        int total() const { return records.size(); }

        void clear();

    private:
        QList<Seen> records;
        QSet<QString> seenKeys;
    };

} // namespace GreenRhythm
