#pragma once

#include <QList>
#include <QString>

namespace GreenRhythm {

    /** Диапазон номеров портов, отданный системой под свои нужды. */
    struct PortRange {
        int from = 0;
        int to = 0;
        bool covers(int port) const { return port >= from && port <= to; }
    };

    /**
     * Состояние портов машины.
     *
     * ЗАЧЕМ ЭТО ВООБЩЕ ЕСТЬ. Windows умеет резервировать номера портов за собой —
     * это делают Hyper-V, WSL и Docker. Программа, попросившая такой номер,
     * получает отказ доступа, и выглядит он как что угодно, только не как
     * «порт занят системой»: у нас это было «подключение не запускается», у
     * чужого лаунчера — «ошибка соединения» и сорванная установка игры.
     *
     * Беда невидима с обеих сторон. Мы не могли её показать, потому что не
     * смотрели; чужая программа — потому что берёт жёстко заданные номера и,
     * не получив их, просто падает. На живой машине владельца так и вышло:
     * динамический диапазон был расширен до 1024-65534 вместо штатных
     * 49152-65535, система нарезала в нём 27 блоков, и один накрыл девять
     * фиксированных портов игрового сервиса. Полночи ушло на поиск.
     *
     * Разбор вынесен сюда отдельно: он чистый, проверяется набором и не зависит
     * ни от окон, ни от запущенной системы.
     */
    struct PortHealth {
        int dynamicFrom = 0;  ///< начало динамического диапазона
        int dynamicCount = 0; ///< сколько номеров в нём
        QList<PortRange> reserved;

        /** Сколько номеров всего забрала себе система. */
        int reservedPorts() const;

        /** Занят ли этот номер системой. */
        bool isReserved(int port) const;

        /**
         * Расширен ли динамический диапазон за штатные пределы.
         *
         * Штатное значение Windows — 49152 и 16384 номеров. Пока диапазон такой,
         * резервы системы падают только в верхнюю часть пространства, и портам
         * приложений ничего не грозит. Стоит его расширить — и резерв может лечь
         * куда угодно, в том числе на фиксированные порты чужих программ.
         */
        bool dynamicRangeWidened() const { return dynamicFrom < 49152; }

        /** Есть ли о чём говорить человеку. */
        bool worthReporting() const;

        /** Приговор человеческим языком; пусто, когда всё в порядке. */
        QString verdict() const;
    };

    /** Разбор вывода `netsh int ipv4 show dynamicport tcp` и `... show excludedportrange`. */
    PortHealth parsePortHealth(const QString &dynamicOutput, const QString &excludedOutput);

} // namespace GreenRhythm
