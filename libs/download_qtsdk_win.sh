#!/bin/bash
set -euo pipefail

# ТУЛЧЕЙН СВЕРЯЕТСЯ ПО СУММЕ.
#
# Здесь приезжает компилятор-рантайм, которым собран весь продукт, — и приезжает
# он архивом из чужого релиза. Прежде он брался вообще без проверок: ни -f, ни
# суммы, ни set -e. Отказ сети оставил бы битый или пустой файл, а подмена в
# чужом релизе прошла бы незамеченной — для VPN-клиента это самый дешёвый путь
# в наш бинарь. Xray в том же выпуске давно прибит версией и sha256, с целым
# абзацем объяснений; тулчейн оставался исключением без причины.
#
# Сумма снята с того самого архива, из которого собраны текущие выпуски, и
# сверена с локальной копией SDK, на которой они собирались.

QT6_URL="https://github.com/MatsuriDayo/nekoray_qt_runtime/releases/download/20220503/Qt6.7.2-Windows-x86_64-VS2022-17.10.3-20240621.7z"
QT6_SHA="e5d34a7d447f8b11d4ad2c29362eb7cfe3ce0621f6139b73a03aeebcff728ec9"

if [ "${DL_QT_VER:-}" == "5.15" ]; then
  # Этой веткой никто не пользуется: во всех сборках DL_QT_VER = 6.7. Оставить
  # её работающей без суммы значит держать незакреплённый путь, о котором никто
  # не помнит. Понадобится — снимите сумму так же, как для 6.7, и впишите сюда.
  echo "сборка с Qt 5.15 не закреплена контрольной суммой и потому отключена" >&2
  exit 1
fi

mkdir -p qtsdk
cd qtsdk

ARCHIVE="qt.7z"
curl -fLSo "$ARCHIVE" "$QT6_URL"

# Проверяем ДО распаковки: разбирать потом, что успело лечь на диск, дороже.
echo "${QT6_SHA}  ${ARCHIVE}" | sha256sum -c -

7z x "$ARCHIVE"
rm "$ARCHIVE"
mv Qt* Qt
