#pragma once

#include <QString>
#include <QStringList>

namespace NekoGui_sys {

    /** Из чего собирается файл автонастройки. Ровно то, что на него влияет. */
    struct PacInput {
        /** Порт местного SOCKS. Всё, что не ушло напрямую, идёт сюда. */
        int socksPort = 0;

        /** Правила «мимо канала» — по одному в строке, как их вводит человек. */
        QString directDomain;
        QString directIp;

        /** Правила «через канал». Проверяются РАНЬШЕ прямых — см. реализацию. */
        QString proxyDomain;
        QString proxyIp;

        /** Правила «никуда». В PAC выражаются единственным доступным способом. */
        QString blockDomain;
    };

    /** Что из правил не удалось выразить — человеку и в журнал, не молча. */
    struct PacNotes {
        /** Правила, которые в PAC невыразимы вовсе (geosite:, geoip:, regexp:). */
        QStringList skipped;
    };

    /**
     * Собрать текст автонастройки прокси.
     *
     * ЧЕГО PAC НЕ УМЕЕТ, и почему об этом обязательно сказать вслух. Язык здесь
     * — обычный JavaScript с горсткой функций, и в нём НЕТ ни geosite, ни geoip:
     * это списки на десятки тысяч записей, которые живут в ядре, а не в
     * браузере. Правила такого вида просто пропускаются — и попадают в
     * notes.skipped, чтобы поддержка не искала причину «почему этот сайт пошёл
     * не туда» вслепую.
     *
     * ПОРЯДОК ПРОВЕРОК — часть договора, а не деталь:
     *   1. служебное и местное (localhost, .local, .lan, .home.arpa, частные
     *      сети, CGNAT) — всегда напрямую;
     *   2. «через канал» — то, что человек назвал явно;
     *   3. «никуда» — блокировка;
     *   4. «мимо канала»;
     *   5. всё остальное — в канал.
     *
     * Пункт 1 стоит первым и не обходится ничем. Он и есть то, ради чего PAC
     * выбран вместо «один адрес на всё»: домашний NAS, принтер и рабочая сеть
     * обязаны остаться достижимыми, что бы ни было написано в остальных
     * правилах.
     *
     * Пункт 2 стоит РАНЬШЕ пункта 4 намеренно. Человек, добавивший домен и туда
     * и туда, почти наверняка хотел провести его через канал: правило «мимо»
     * чаще всего унаследовано из общего списка, а «через» дописано руками
     * только что.
     */
    QString BuildPac(const PacInput &in, PacNotes *notes = nullptr);

} // namespace NekoGui_sys
