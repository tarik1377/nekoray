#pragma once

#include <QString>
#include <QStringList>

namespace NekoGui_sys {

    /**
     * Системный прокси macOS — со снимком того, что было до нас.
     *
     * ПОЧЕМУ НЕ ПРАВКА ВЕНДОРНОГО QvProxyConfigurator. В нём нет самого понятия
     * снимка: ClearSystemProxy просто гасит прокси на всех сетевых службах.
     * Человеку, у которого свой корпоративный прокси был настроен до нас, он
     * стирает настройку, и восстановить её нам уже нечем — мы никогда не знали,
     * что там было. Это не гипотеза: именно так вендорный код и написан.
     *
     * ПОРЯДОК ДЕЙСТВИЙ СТРОГИЙ И ОБСУЖДЕНИЮ НЕ ПОДЛЕЖИТ:
     *   1. прочитать текущее состояние всех служб;
     *   2. записать снимок на диск и СБРОСИТЬ его туда же (flush);
     *   3. только потом применять своё.
     * Наоборот — окно, в котором падение приложения оставляет систему без
     * интернета и без единого следа о том, как было. Тот же файл служит
     * признаком аварии: если он найден при следующем запуске, значит прошлый
     * раз закончился не по-хорошему, и состояние надо вернуть.
     *
     * ЧТО ЭТОТ РЕЖИМ НЕ ПОКРЫВАЕТ — и об этом надо говорить человеку прямо, а
     * не выяснять с ним потом в переписке. Системный прокси уважают браузеры и
     * большинство обычных программ. Его НЕ уважают: терминал (curl, git, ssh),
     * Docker, часть игр и всё, что ходит своим стеком. Для них трафик идёт
     * мимо. Туннель таких дыр не имеет — в этом и разница между режимами.
     */
    namespace MacProxy {

        /**
         * Включить системный прокси, указав системе наш файл автонастройки.
         *
         * Снимок берётся ровно один раз — при первом включении. Повторный вызов
         * (например, после смены правил) снимок НЕ перезаписывает: иначе вторым
         * включением мы бы запомнили собственные настройки как «то, что было
         * до нас», и восстанавливать стало бы нечего.
         *
         * false — не применилось. На машинах под управлением организации
         * networksetup вправе отказать, и молчать об этом нельзя: человек
         * решит, что прокси включён, а он не включён.
         */
        bool Enable(const QString &pacUrl);

        /** Вернуть всё, как было до нас, и убрать снимок. */
        bool Disable();

        /**
         * Проверить при старте, не остался ли снимок от прошлого раза.
         *
         * Остался — значит прошлый запуск закончился падением или убийством
         * процесса, и в системе до сих пор стоят наши настройки. Зовётся один
         * раз, до всего остального.
         */
        void RestoreIfCrashed();

        /** Сетевые службы, как их называет система. Пусто — не удалось узнать. */
        QStringList NetworkServices();

        /**
         * Что сейчас настроено в системе — строками для человека.
         *
         * Нужно «Починить сеть»: половина обращений вида «после падения
         * приложения перестал работать браузер» объясняется тем, что в системе
         * остался наш адрес автонастройки, ведущий на порт, которого больше
         * нет. Показать это надо ДО того, как что-то трогать, — иначе человек
         * не поймёт, что именно чинят.
         *
         * Отдельно отмечается чужой прокси: его мы не трогаем ни при каких
         * условиях, но знать о нём человеку полезно.
         */
        QStringList Report();

        /**
         * Осталось ли в системе НАШЕ. Отличается от «прокси настроен вообще»:
         * чужой корпоративный прокси — не наша забота и не наша поломка.
         */
        bool OursIsLeftBehind();

    } // namespace MacProxy

} // namespace NekoGui_sys
