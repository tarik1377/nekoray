#pragma once

#include <QString>
#include <QStringList>

namespace NekoGui_sys {

    /** Чужой туннель, замеченный в таблице маршрутов. Ничего не меняет. */
    struct ForeignTunnel {
        /** Как его зовёт система. Показывается человеку. */
        QString name;

        /** Куда через него идут маршруты. Может быть пусто. */
        QStringList prefixes;

        /**
         * Владеет ли он половиной адресного пространства.
         *
         * Признак того, что это полнотуннельный VPN: 0.0.0.0/1 и 128.0.0.0/1 —
         * приём, которым перехватывают весь трафик, не трогая маршрут по
         * умолчанию. С нашим туннелем такой ужиться не может по определению —
         * два полных туннеля на одной машине несовместимы.
         */
        bool ownsHalfTheInternet = false;
    };

    /**
     * Найти чужие туннели. ТОЛЬКО ЧТЕНИЕ — ни одного изменения в системе.
     *
     * ЗАЧЕМ. Чтобы предупредить заранее и сказать поддержке, что происходит. У
     * человека может быть поднят домашний wireguard до своей сети, корпоративный
     * клиент, Tailscale, WARP. С разделённым туннелем (AllowedIPs вида
     * 192.168.1.0/24) наш туннель уживается: маршрут длиннее нашего и выигрывает
     * по длине префикса. С полнотуннельным — нет, и об этом надо сказать ДО
     * включения, а не после того, как у человека отвалится рабочая сеть.
     *
     * ЧЕГО ЭТА ФУНКЦИЯ НАМЕРЕННО НЕ ДЕЛАЕТ — не подставляет найденное в
     * исключения сама. Полнотуннельный чужой VPN владеет половиной адресного
     * пространства, и наивное «нашёл — исключил» выключило бы обход для половины
     * интернета. Найденное показывается человеку, и подставляет он его сам —
     * кнопкой в настройках туннеля.
     *
     * И не выключает адаптеры. Ровно этим занималась «Починить сеть Windows», и
     * именно поэтому у людей гас домашний wireguard.
     *
     * Пустой список означает «не нашли» ИЛИ «не смогли посмотреть» — эти два
     * случая здесь не различаются намеренно: ни в одном из них делать нечего.
     */
    QList<ForeignTunnel> DetectForeignTunnels();

    /** Найденное одной строкой для журнала. Пусто — писать нечего. */
    QString DescribeForeignTunnels(const QList<ForeignTunnel> &found);

} // namespace NekoGui_sys
