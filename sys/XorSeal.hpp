#pragma once

#include <QByteArray>

/**
 * Общая часть запечатки для платформ БЕЗ настоящего хранилища ключей.
 *
 * ЗАЧЕМ ОБЩАЯ. Linux и macOS делают одно и то же: выводят ключ из чего-то
 * своего и накладывают его на данные. Различается ровно источник ключа, и
 * держать ради этого две копии одного алгоритма — значит однажды починить его в
 * одном файле и забыть про второй.
 *
 * ЧТО ЭТО ДАЁТ. Ровно одно, и ради него слой заводился: файл, скопированный на
 * другую машину, не открывается. Плюс в отчёт поддержки не попадают читаемые
 * ключи, если человек приложит файл.
 *
 * ЧЕГО НЕ ДАЁТ. Ничего от того, кто уже выполняет код на этой машине от имени
 * этого пользователя. Обещать здесь стойкость — врать, а неверное обещание
 * опаснее отсутствующего: на него полагаются.
 *
 * ЗАЧЕМ ОБРАМЛЕНИЕ, А НЕ ГОЛЫЙ XOR. Голый XOR обратим ЛЮБЫМ ключом: чужой файл
 * «распечатывается» в мусор, и отличить «не наш файл» от «наш, но испорченный»
 * невозможно. На Windows DPAPI такое различает, и поведение платформ
 * расходилось — набор проверок это и поймал, упав в контейнере. Метка и
 * короткий отпечаток дают то же различение: не сошлось — значит не наше, и
 * наружу уходит пустота, а не мусор.
 */
namespace XorSeal {

    /** Запечатать. Пустой ключ или пустые данные — пустой ответ (отказ). */
    QByteArray Seal(const QByteArray &plain, const QByteArray &key);

    /** Распечатать. Не наше, испорченное или чужое — пустой ответ. */
    QByteArray Unseal(const QByteArray &sealed, const QByteArray &key);

} // namespace XorSeal
