#!/bin/sh
set -e
set -x

if [ "$(id -u)" -ne 0 ]; then
  echo "[Warning] Tun script not running as root"
fi

# КАВЫЧКИ ВОКРУГ ПУТИ ОБЯЗАТЕЛЬНЫ. На macOS каталог настроек — это
# ~/Library/Application Support/…, то есть путь с пробелом. Без кавычек cd
# уходит в "Application", падает по set -e, и человек видит, что туннель
# включился и сразу выключился, — без единого внятного сообщения.
BASEDIR=$(dirname "$0")
cd "$BASEDIR"

# Правила iptables — ЛИНУКСОВЫЕ, и только линуксовые. На macOS их нет вовсе:
# команда не находится, set -e останавливает скрипт, и ядро не запускается
# никогда. Тот же признак нужен и в stop, иначе выход из туннеля падал бы на
# том же месте, не сняв за собой ничего.
is_linux() {
  [ "$(uname -s)" = "Linux" ]
}

pre_start_linux() {
  is_linux || return 0
  command -v iptables >/dev/null 2>&1 || return 0
  # for Tun2Socket
  iptables -I INPUT -s 172.19.0.2 -d 172.19.0.1 -p tcp -j ACCEPT
  ip6tables -I INPUT -s fdfe:dcba:9876::2 -d fdfe:dcba:9876::1 -p tcp -j ACCEPT
}

# НОМЕР ПРОЦЕССА И ЖУРНАЛ ПОМОЩНИКА — В ФАЙЛЫ РЯДОМ С КОНФИГОМ, и это не
# удобство, а единственный канал связи. На macOS скрипт запускает osascript, а
# тот отдаёт вывод только ПОСЛЕ завершения команды: пока ядро живёт, приложение
# не видит от него ни строки, и «туннель не работает» долго не имело
# подробностей. Журнал приложение читает по мере записи; номер процесса нужен,
# чтобы снимать туннель точечно, а не убивать все ядра от root подряд.
#
# Имена файлов закреплены набором test/TunHelperTest.cpp вместе с
# main/TunHelper.cpp: разойдутся — набор скажет.
PID_FILE="$BASEDIR/tun-helper.pid"
LOG_FILE="$BASEDIR/tun-helper.log"

start() {
  # СИМВОЛИЧЕСКИЕ ССЫЛКИ ОТВЕРГАЮТСЯ — И ДО ВСЕГО ОСТАЛЬНОГО. Скрипт работает от
  # root, а каталог принадлежит человеку: подложенная туда ссылка с именем
  # журнала заставила бы root писать в чужой файл. Отказ идёт первым: правила
  # iptables ниже уже нельзя было бы снять, выйдя посередине.
  #
  # set -C (noclobber) делает обе записи через > атомарными: ядро создаёт файл с
  # O_EXCL и откажет на любом уже существующем пути, включая ссылку,
  # подставленную между проверкой и записью.
  for f in "$LOG_FILE" "$PID_FILE"; do
    if [ -L "$f" ]; then
      echo "refusing symlink: $f" >&2
      exit 1
    fi
  done
  rm -f "$LOG_FILE" "$PID_FILE"
  set -C
  : > "$LOG_FILE"
  chmod 644 "$LOG_FILE" 2>/dev/null || true
  pre_start_linux
  echo "helper: start $(date) uid=$(id -u) config=$CONFIG_PATH" >> "$LOG_FILE"
  "./greenrhythm_core" run -c "$CONFIG_PATH" >> "$LOG_FILE" 2>&1 &
  core=$!
  echo $core > "$PID_FILE"
  set +C
  chmod 644 "$PID_FILE" 2>/dev/null || true
  # СИГНАЛ ПЕРЕДАЁТСЯ ЯДРУ, А НЕ ГЛОТАЕТСЯ ОБОЛОЧКОЙ. Без этого выход из системы
  # или её выключение убивали только оболочку: ядро оставалось жить от root с
  # поднятыми маршрутами, а файл с номером — на диске, и следующий запуск
  # верил ему. sing-tun снимает маршруты и возвращает DNS в Close(), поэтому
  # ядру нужен именно сигнал, а не смерть родителя.
  trap 'kill -2 $core 2>/dev/null || true' INT TERM HUP
  # ОЖИДАНИЕ ЧЕРЕЗ ||: под set -e ненулевой код от wait оборвал бы скрипт до
  # уборки, и файл с номером пережил бы сам процесс.
  rc=0
  wait $core || rc=$?
  echo "helper: core exited rc=$rc $(date)" >> "$LOG_FILE"
  rm -f "$PID_FILE"
  return $rc
}

stop() {
  is_linux || return 0
  command -v iptables >/dev/null 2>&1 || return 0
  iptables -D INPUT -s 172.19.0.2 -d 172.19.0.1 -p tcp -j ACCEPT
  ip6tables -D INPUT -s fdfe:dcba:9876::2 -d fdfe:dcba:9876::1 -p tcp -j ACCEPT
}

# ОТКАЗ СТАРТА БОЛЬШЕ НЕ ГЛУШИТСЯ. Здесь стояло `start || true`, и это значило,
# что не поднявшийся туннель выглядел поднявшимся: скрипт выходил с нулём,
# приложение считало включение удавшимся, а человек оставался без туннеля и без
# единого слова о том, почему.
#
# У stop `|| true` остаётся намеренно: не сумев прибрать за собой, выходить с
# ошибкой незачем — прибирать больше нечего, а отказ на выходе выглядел бы как
# новая поломка.
# КОД ВЫХОДА ЯДРА ДОЕЗЖАЕТ ДО ПРИЛОЖЕНИЯ, а уборка идёт в любом случае: без
# `|| rc=$?` set -e оборвал бы скрипт на неудавшемся start, и stop не
# выполнился бы вовсе.
rc=0
if [ "$1" != "stop" ]; then
  start || rc=$?
fi

stop || true
exit $rc
