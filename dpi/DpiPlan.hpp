#pragma once

#include "dpi/DpiCatalog.hpp"

#include <QString>
#include <QStringList>

/**
 * План запуска winws: аргументы и содержимое списков.
 *
 * ЧИСТАЯ ФУНКЦИЯ. Ни сети, ни файлов, ни системы — вход в структуре, выход в
 * структуре. Поэтому её можно проверить золотым тестом целиком, а всё, что
 * трогает Windows, живёт отдельно в DpiModule.
 *
 * ЧТО ИЗМЕРЕНО, А НЕ ПРЕДПОЛОЖЕНО (конструктор фильтра wf_make_filter из
 * nfq/nfqws.c 72.13, собранный и запущенный отдельно):
 *
 *  — --wf-raw-part соединяется с портовым конструктором через «или», не через
 *    «и». Написав туда «исключить туннель», мы бы не исключили ничего, а
 *    ДОБАВИЛИ ветку, забирающую в пользовательский режим всё вне туннеля.
 *    Поэтому его здесь нет и быть не должно.
 *
 *  — --wf-iface даёт «ifIdx=N and subIfIdx=M and» на ВЕРХНЕМ уровне, перед
 *    всей группой. Это и есть ограничение: смотреть только на физический
 *    адаптер. Пакеты игры, уходящие в наш туннель, winws тогда не видит вовсе.
 *
 *  — Наш собственный туннель к серверу уходит по тому же адаптеру и в поле
 *    зрения попадёт. Его не надо исключать из ЗАХВАТА — достаточно исключить
 *    из ПОРЧИ: --ipset-exclude с адресами сервера в каждом профиле. Захват без
 *    порчи безвреден.
 *
 * ПУСТОЙ СПИСОК У ZAPRET ОЗНАЧАЕТ «НЕТ СПИСКА», то есть дурить всех: так
 * Flowseal делает режим «IPSet any». Одна ошибка в записи файла превратила бы
 * точечный модуль в глобальный. Поэтому в каждом списке всегда стоит
 * сторожевая строка, и тест проверяет, что ни один файл не пуст.
 */
namespace GreenRhythm::Dpi {

    struct PlanInput {
        /** Индекс физического адаптера для --wf-iface. 0 — не ограничивать (только тесты). */
        int ifIndex = 0;
        /** Домены, которые защищаем (без «domain:», без «full:»). */
        QStringList hosts;
        /** Адреса или подсети, которые защищаем. */
        QStringList ips;
        /** Адреса, которые НЕ трогать ни при каких условиях: сервер профиля. */
        QStringList excludeIps;
        /** Стратегия из каталога. */
        Strategy strategy;
        /** Каталог с winws и заготовками. */
        QString binDir;
        /** Каталог, куда лягут списки. */
        QString listDir;
    };

    struct Plan {
        QStringList args;
        QString hostlistPath, ipsetPath, excludePath;
        QString hostlistText, ipsetText, excludeText;
        /** Домены, которые модуль не умеет выразить (ключевые слова, geosite). */
        QStringList uncovered;
        /** Отпечаток плана: тот же вход — тот же отпечаток. По нему решаем, перезапускать ли winws. */
        QString hash;
    };

    Plan buildPlan(const PlanInput &in);

    /**
     * Домены из списка «напрямую» схемы маршрутов в том виде, какой понимает
     * hostlist. Возвращает только то, что выразимо; остальное — в uncovered.
     */
    QStringList hostsFromDirectDomains(const QString &directDomain, QStringList *uncovered);

} // namespace GreenRhythm::Dpi
